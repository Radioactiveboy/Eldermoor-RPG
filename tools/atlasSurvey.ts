/**
 * Surveys the outdoor maps for the world map's drawing (scenes/MapScene.ts): what covers each
 * patch of ground (trees, water, a road, hills, tilled fields, a wall), the buildings and other
 * landmarks worth a picture, and the places' names. The result is written to
 * src/world/atlasSurvey.ts by `npm run atlas`, so the map can be drawn from the real ground
 * without the map files (which only download when their area is entered);
 * tests/unit/atlasSurvey.test.ts fails if it's out of date with the maps.
 */
import { MONASTERY_WALL_Y } from '../src/world/landmarks';
import { MapData, Prop, Terrain } from '../src/world/MapData';

/** Tiles along each side of a surveyed patch. */
export const CELL = 3;

/** A thing drawn as its own little picture on the map. */
export type FeatureKind = 'house' | 'inn' | 'church' | 'hall' | 'tower' | 'cave' | 'willow' | 'gate' | 'well' | 'cottage';

export interface Survey {
  /** One string per row of patches, a letter a patch: W water, T trees, R road, P paving, H rocks, F fields, X wall, . open ground. */
  ground: string[];
  /** [kind, x, y, w, h], in tiles. */
  features: Array<[FeatureKind, number, number, number, number]>;
  /** [name, x, y], in tiles. */
  names: Array<[string, number, number]>;
}

const FEATURES: Array<[RegExp, FeatureKind]> = [
  [/^bld-cottage$|^bld-hut$/, 'cottage'],
  [/^bld-inn$/, 'inn'],
  [/^bld-/, 'house'],
  [/^abbey-chapel$/, 'church'],
  [/^abbey-(dorter|refectory|infirmary|scriptorium|lodging)$/, 'hall'],
  [/^(mon-tower|nw-watchtower)$/, 'tower'],
  [/^(cave|den)-entrance$/, 'cave'],
  [/^plains-willow$/, 'willow'],
  [/^((toll|mon)-gate-open|palisade-gateway)$/, 'gate'],
  [/^mkt-well$/, 'well'],
];

/**
 * @param skipAbove rows above this are left out: the monastery's map shows the abbey over its
 * wall, which the world map draws as a place of its own
 */
export function survey(map: MapData, skipAbove = 0): Survey {
  const cols = Math.ceil(map.width / CELL);
  const rows = Math.ceil(map.height / CELL);
  // A patch with a stretch of wall in it is wall: the monastery's, or two or more tiles of a palisade
  // (so a patch with only the end of one beside a gateway stays open, and the way through shows).
  const wallTiles = new Map<string, number>();
  for (const o of map.objects ?? []) {
    if (o.ty < skipAbove) continue;
    const weight = /^mon-wall/.test(o.key) ? 2 : /^(palisade|toll-palisade)/.test(o.key) && o.key !== 'palisade-tower' && o.key !== 'palisade-gateway' ? 1 : 0;
    if (!weight) continue;
    const k = `${Math.floor(o.tx / CELL)},${Math.floor(o.ty / CELL)}`;
    wallTiles.set(k, (wallTiles.get(k) ?? 0) + weight);
  }
  const walls = new Set([...wallTiles].filter(([, n]) => n >= 2).map(([k]) => k));
  const ground: string[] = [];
  for (let cy = 0; cy < rows; cy++) {
    let row = '';
    for (let cx = 0; cx < cols; cx++) {
      const n = { water: 0, trees: 0, road: 0, paved: 0, rock: 0, soil: 0 };
      for (let ty = cy * CELL; ty < Math.min(map.height, (cy + 1) * CELL); ty++) {
        for (let tx = cx * CELL; tx < Math.min(map.width, (cx + 1) * CELL); tx++) {
          const t = map.terrain[ty][tx];
          const p = map.props[ty][tx];
          if (t === Terrain.Water) n.water++;
          if (t === Terrain.Dirt || t === Terrain.Sand) n.road++;
          if (t === Terrain.Stone) n.paved++;
          if (t === Terrain.Soil) n.soil++;
          if (t === Terrain.Cave || p === Prop.Rock) n.rock++;
          if (p === Prop.Tree) n.trees++;
        }
      }
      const above = (cy + 1) * CELL <= skipAbove;
      row += above ? '.'
        : walls.has(`${cx},${cy}`) ? 'X'
        : n.water >= 4 ? 'W'
        : n.trees >= 2 ? 'T'
        : n.soil >= 3 ? 'F'
        : n.rock >= 2 ? 'H'
        : n.road >= 3 ? 'R'
        : n.paved >= 5 ? 'P'
        : '.';
    }
    ground.push(row);
  }
  const features: Survey['features'] = [];
  for (const o of map.objects ?? []) {
    if (o.ty < skipAbove) continue;
    const kind = FEATURES.find(([re]) => re.test(o.key))?.[1];
    if (kind) features.push([kind, o.tx, o.ty, o.w, o.h]);
  }
  const names: Survey['names'] = (map.landmarks ?? [])
    .filter((l) => l.gy >= skipAbove)
    .map((l) => [l.name, Math.round(l.gx * 10) / 10, Math.round(l.gy * 10) / 10]);
  return { ground, features, names };
}

/** The monastery's survey leaves out what's over its wall. */
export const SKIP_ABOVE: Record<string, number> = { monastery: MONASTERY_WALL_Y };

/** The generated file's text. */
export function surveyFile(surveys: Record<string, Survey>): string {
  const body = Object.entries(surveys)
    .map(([id, s]) => `  ${JSON.stringify(id)}: {\n    ground: [\n${s.ground.map((r) => `      '${r}',`).join('\n')}\n    ],\n    features: ${JSON.stringify(s.features)},\n    names: ${JSON.stringify(s.names)},\n  },`)
    .join('\n');
  return `// Generated by \`npm run atlas\` (tools/atlasSurvey.ts) from the outdoor maps: don't edit by hand.
// What covers the ground in each area, for the world map's drawing (see scenes/MapScene.ts).
import type { AreaId } from './MapData';

export type FeatureKind = ${FEATURES_KINDS};

export interface AreaSurvey {
  /** One string per row of ${CELL}x${CELL}-tile patches: W water, T trees, R road, P paving, H rocks, F fields, X wall, . open ground. */
  ground: string[];
  /** [kind, x, y, w, h], in tiles. */
  features: Array<[FeatureKind, number, number, number, number]>;
  /** [name, x, y], in tiles. */
  names: Array<[string, number, number]>;
}

export const SURVEY_CELL = ${CELL};

export const SURVEY: Partial<Record<AreaId, AreaSurvey>> = {
${body}
};
`;
}

const FEATURES_KINDS = ['house', 'inn', 'church', 'hall', 'tower', 'cave', 'willow', 'gate', 'well', 'cottage'].map((k) => `'${k}'`).join(' | ');
